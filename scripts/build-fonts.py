"""Rebuild the vendored Latin web fonts in src/assets/fonts/.

The app never requests fonts from the network:
  * Cinzel             (display capitals, Latin subset)      -> vendored here
  * Cormorant Garamond (numerals / italics, Latin subset)    -> vendored here
  * Noto Serif SC 600  -> the @fontsource/noto-serif-sc npm package (Vite bundles
                          its unicode-range slices locally); fonts.css imports it.
All three are licensed under the SIL Open Font License 1.1.

Usage (pip install fonttools brotli):
  python scripts/build-fonts.py <google-fonts-ofl-dir>
where <google-fonts-ofl-dir> is a checkout of github.com/google/fonts/ofl.
"""
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

OFL = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "assets", "fonts")
LATIN = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2116,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"


def parse(spec):
    cps = set()
    for part in spec.replace(" ", "").split(","):
        part = part.replace("U+", "")
        if not part:
            continue
        a, _, b = part.partition("-")
        cps.update(range(int(a, 16), int(b or a, 16) + 1))
    return cps


def make_subset(src, cps, dst):
    font = TTFont(src)
    have = [c for c in cps if c in font.getBestCmap()]
    if not have:
        return False
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.hinting = False
    opts.desubroutinize = True
    s = subset.Subsetter(options=opts)
    s.populate(unicodes=have)
    s.subset(font)
    font.flavor = "woff2"
    font.save(dst)
    return True


os.makedirs(OUT, exist_ok=True)
css = []
latin_faces = [
    ("Tavern Display", "cinzel/Cinzel[wght].ttf", "cinzel-latin.woff2", "400 900", "normal"),
    ("Tavern Garamond", "cormorantgaramond/CormorantGaramond[wght].ttf", "cormorant-latin.woff2", "300 700", "normal"),
    ("Tavern Garamond", "cormorantgaramond/CormorantGaramond-Italic[wght].ttf", "cormorant-italic-latin.woff2", "300 700", "italic"),
]
for family, src, name, weight, style in latin_faces:
    make_subset(os.path.join(OFL, src), parse(LATIN), os.path.join(OUT, name))
    css.append(
        f"@font-face {{\n  font-family: '{family}';\n  font-style: {style};\n  font-weight: {weight};\n"
        f"  font-display: swap;\n  src: url(./{name}) format('woff2');\n  unicode-range: {LATIN.replace(',', ', ')};\n}}"
    )

header = (
    '@import "@fontsource/noto-serif-sc/600.css";\n\n'
    "/* Generated by scripts/build-fonts.py. Cinzel + Cormorant Garamond are vendored here;\n"
    "   Noto Serif SC 600 comes from @fontsource/noto-serif-sc (bundled locally by Vite).\n"
    "   All three are licensed under the SIL Open Font License 1.1 (see the OFL-*.txt files in this folder). */\n\n"
)
with open(os.path.join(OUT, "fonts.css"), "w") as f:
    f.write(header + "\n\n".join(css) + "\n")
